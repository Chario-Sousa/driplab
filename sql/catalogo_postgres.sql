create table public.categoria (
    id_categoria integer generated by default as identity primary key,
    nome_categoria varchar(80) not null
);

create table public.colecao (
    id_colecao integer generated by default as identity primary key,
    nome_colecao varchar(120) not null,
    data_lancamento timestamp not null,
    ativa boolean not null default true,
    data_encerramento timestamp,
    limite_pecas integer not null check (limite_pecas >= 0)
);

create table public.produto (
    id_produto integer generated by default as identity primary key,
    nome_produto varchar(150) not null,
    descricao_produto text not null,
    imagem_url varchar(500),
    preco numeric(10, 2) not null check (preco >= 0),
    estoque integer not null default 0 check (estoque >= 0),
    fk_categoria_id_categoria integer not null references public.categoria
        on delete restrict on update cascade,
    fk_colecao_id_colecao integer references public.colecao
        on delete set null on update cascade
);

create index on public.produto (fk_categoria_id_categoria);
create index on public.produto (fk_colecao_id_colecao);

alter table public.categoria enable row level security;
alter table public.colecao enable row level security;
alter table public.produto enable row level security;

revoke all on public.categoria, public.colecao, public.produto
    from anon, authenticated;

with categorias as (
    insert into public.categoria (nome_categoria)
    values ('Camisetas'), ('Moletons'), ('Calças'), ('Acessórios'), ('Jaquetas')
    returning id_categoria, nome_categoria
), colecao_inicial as (
    insert into public.colecao (
        nome_colecao, data_lancamento, ativa, data_encerramento, limite_pecas
    )
    values ('Drop inicial', '2026-11-14 02:21:11', true, '2026-12-14 02:21:11', 100)
    returning id_colecao
)
insert into public.produto (
    nome_produto, descricao_produto, preco, estoque,
    fk_categoria_id_categoria, fk_colecao_id_colecao
)
select
    dados.nome_produto, dados.descricao_produto, dados.preco, dados.estoque,
    categorias.id_categoria, colecao_inicial.id_colecao
from (values
    (1, 'T-Shirt Logo', 'Camiseta streetwear com logo DripLab.', 159.90, 25, 'Camisetas'),
    (2, 'Moletom Essential', 'Moletom streetwear essencial do drop.', 349.90, 10, 'Moletons'),
    (3, 'Cargo Pants', 'Calça cargo streetwear.', 299.90, 15, 'Calças'),
    (4, 'Boné DripLab', 'Boné streetwear DripLab.', 129.90, 30, 'Acessórios'),
    (5, 'Jaqueta Tech', 'Jaqueta streetwear para o drop inicial.', 399.90, 8, 'Jaquetas')
) as dados (ordem, nome_produto, descricao_produto, preco, estoque, nome_categoria)
join categorias using (nome_categoria)
cross join colecao_inicial
order by dados.ordem;
